"""Allowlisted security event codes, with IDs only and no arbitrary payloads."""

from enum import StrEnum

from sqlalchemy.orm import Session

from campushallen.database.models import AuditEvent


class Event(StrEnum):
    RECONCILIATION_APPROVED = "RECONCILIATION_APPROVED"
    LIVE_BOOKING_ENABLED = "LIVE_BOOKING_ENABLED"
    LIVE_BOOKING_DISABLED = "LIVE_BOOKING_DISABLED"
    WEBSITE_LOGIN_FAILED = "WEBSITE_LOGIN_FAILED"
    WEBSITE_LOGIN_LOCKED = "WEBSITE_LOGIN_LOCKED"
    WEBSITE_LOGIN_SUCCESS = "WEBSITE_LOGIN_SUCCESS"
    WEBSITE_LOGIN_LOCK_EXPIRED = "WEBSITE_LOGIN_LOCK_EXPIRED"
    USER_REGISTERED = "USER_REGISTERED"
    USER_CREATED = "USER_CREATED"
    USER_DELETED = "USER_DELETED"
    ADMIN_PROMOTED = "ADMIN_PROMOTED"
    ADMIN_DEMOTED = "ADMIN_DEMOTED"
    LOGIN_SUCCESS = "LOGIN_SUCCESS"
    LOGIN_FAILED = "LOGIN_FAILED"
    LOGOUT = "LOGOUT"
    SESSIONS_REVOKED = "SESSIONS_REVOKED"
    PASSWORD_CHANGED = "PASSWORD_CHANGED"
    CAMPUSHALLEN_CONNECTED = "CAMPUSHALLEN_CONNECTED"
    CAMPUSHALLEN_RECONNECTED = "CAMPUSHALLEN_RECONNECTED"
    ACCOUNT_DISABLED = "ACCOUNT_DISABLED"
    ACCOUNT_ENABLED = "ACCOUNT_ENABLED"
    ACCOUNT_DISCONNECTED = "ACCOUNT_DISCONNECTED"
    ACCOUNT_DELETED = "ACCOUNT_DELETED"
    STORED_CREDENTIAL_ENABLED = "STORED_CREDENTIAL_ENABLED"
    STORED_CREDENTIAL_REMOVED = "STORED_CREDENTIAL_REMOVED"
    STORED_CREDENTIAL_REPLACED = "STORED_CREDENTIAL_REPLACED"
    BOOKING_RULE_CREATED = "BOOKING_RULE_CREATED"
    BOOKING_RULE_UPDATED = "BOOKING_RULE_UPDATED"
    BOOKING_RULE_DELETED = "BOOKING_RULE_DELETED"
    INVITE_CREATED = "INVITE_CREATED"
    INVITE_USED = "INVITE_USED"
    INVITE_REVOKED = "INVITE_REVOKED"
    TOKEN_EXPIRED = "TOKEN_EXPIRED"
    REAUTH_SUCCESS = "REAUTH_SUCCESS"
    REAUTH_FAILED = "REAUTH_FAILED"
    RECONNECT_REQUIRED = "RECONNECT_REQUIRED"


def audit(
    db: Session,
    code: Event,
    *,
    user_id: int | None = None,
    actor_id: int | None = None,
    account_id: int | None = None,
) -> None:
    db.add(
        AuditEvent(code=code.value, user_id=user_id, actor_user_id=actor_id, account_id=account_id)
    )
